// Train the shipped classifier on the full generated corpus and write
// src/model.js. Run: node ml/train.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generate } from "./corpus.mjs";
import { quantize, train, vectorize } from "./lr.mjs";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const { malicious, benign } = generate({ seed: 1 });
const model = quantize(train(vectorize([...malicious, ...benign])));
const body = JSON.stringify({ version: 1, buckets: model.w.length, b: model.b, w: model.w });
writeFileSync(join(ROOT, "src", "model.js"),
  "// Generated by ml/train.mjs: logistic regression over hashed char n-grams.\n" +
  "// Do not edit by hand; retrain instead.\n" +
  "(function (root) {\n" +
  `  const m = ${body};\n` +
  '  if (typeof module !== "undefined" && module.exports) module.exports = m;\n' +
  "  else root.ClickFixModel = m;\n" +
  '})(typeof globalThis !== "undefined" ? globalThis : this);\n');
console.log(`trained on ${malicious.length} malicious + ${benign.length} benign; nonzero weights: ${model.w.filter((x) => x).length}`);
